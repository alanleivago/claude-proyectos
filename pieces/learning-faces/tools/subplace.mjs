// subplace.mjs: caption placement from an emptiness map (round 9, the Urbn way). For each caption chunk: render 3 frames of
// its span with captions off (window.NOCAP), score every candidate block position on a 24-px grid by how dark and flat
// the pixels under it (plus a 40-px margin) are across all 3 frames (max over frames), keep clear of the tag / HUD
// corners and the frame edge, prefer a different spot from the previous chunk; fall back to the bottom when nothing is
// empty enough. Writes src/subpos.js { key(t0): [cx, y] } and review/qa/subplace.json (scores, for the text check).
import { createRequire } from 'node:module'; import { execSync } from 'node:child_process'; import fs from 'node:fs'; import path from 'node:path'; import { pathToFileURL } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require(path.join(execSync('npm root -g').toString().trim(), 'playwright'));
const P = path.resolve(process.argv[2] || 'pieces/learning-faces');
const b = await chromium.launch(), pg = await b.newPage();
await pg.goto(pathToFileURL(path.join(P, 'index.html')).href + '?export=1'); await pg.waitForFunction(() => window.TIMELINE && window.renderFrame);
const res = await pg.evaluate(() => {
  window.NOCAP = true;
  const T = window.TIMELINE, c = document.createElement('canvas'); c.width = T.width; c.height = T.height;
  const G = 24, gw = 80, gh = 45, s = document.createElement('canvas'); s.width = gw; s.height = gh; const sg = s.getContext('2d', { willReadFrequently: true });
  const out = {}, info = []; let prev = null;
  const lumaAt = (t) => { window.renderFrame(Math.round(t * T.fps) / T.fps, c); sg.drawImage(c, 0, 0, gw, gh); const d = sg.getImageData(0, 0, gw, gh).data; const L0 = new Float32Array(gw * gh); for (let i = 0; i < L0.length; i++) L0[i] = d[i * 4];
    // keep away from the subject: each cell takes the brightest value within 2 cells (48 px), so a block can't sit right
    // beside a face or on dark hair next to it
    const L = new Float32Array(gw * gh); for (let y = 0; y < gh; y++) for (let x = 0; x < gw; x++) { let m = 0; for (let dy = -2; dy <= 2; dy++) for (let dx = -2; dx <= 2; dx++) { const yy = y + dy, xx = x + dx; if (yy >= 0 && yy < gh && xx >= 0 && xx < gw) m = Math.max(m, L0[yy * gw + xx]); } L[y * gw + x] = 0.5 * L0[y * gw + x] + 0.5 * m; } return L; };
  for (const ch of SUBS) {
    const S = SUB_S, bw = Math.max(...ch.rows.map((r) => afW(r.toLowerCase()))) * S + 40, bh = ch.rows.length * 12 * S + 30;
    const ts = [ch.t0 + 0.05, (ch.t0 + ch.end) / 2, ch.end - 0.06].filter((t) => t < T.duration);
    const Ls = ts.map(lumaAt);
    const cw = Math.ceil((bw + 80) / G), chh = Math.ceil((bh + 80) / G);
    let best = null;
    for (let y0 = 3; y0 + chh <= gh - 2; y0++) for (let x0 = 2; x0 + cw <= gw - 2; x0++) {
      const cx = (x0 + cw / 2) * G, top = (y0 * G) + 40;
      if (top < 140 && cx - bw / 2 < 860) continue;                                  // the chapter tag (top-left)
      let cost = 0;
      for (const L of Ls) {
        let sum = 0, mx = 0, ed = 0;
        for (let y = y0; y < y0 + chh; y++) for (let x = x0; x < x0 + cw; x++) { const v = L[y * gw + x]; sum += v; mx = Math.max(mx, v); if (x > x0) ed += Math.abs(v - L[y * gw + x - 1]); }
        const n = cw * chh; cost = Math.max(cost, sum / n / 255 + 1.2 * Math.pow(mx / 255, 2) + 1.5 * ed / n / 255);
      }
      cost += 0.05 * Math.abs(cx - 960) / 960;                                       // a slight pull to the centre
      if (prev && Math.hypot(cx - prev[0], top - prev[1]) < 120) cost += 0.08;       // move between lines
      if (!best || cost < best.cost) best = { cost, cx, top };
    }
    const key = ch.t0.toFixed(2);
    if (!best || best.cost > 9) { info.push({ key, text: ch.rows.join(' / '), fallback: true, cost: best?.cost }); prev = null; continue; }
    out[key] = [Math.round(best.cx), Math.round(best.top)]; prev = out[key];
    info.push({ key, text: ch.rows.join(' / '), x: out[key][0], y: out[key][1], w: bw, h: bh, cost: +best.cost.toFixed(3) });
  }
  return { out, info };
});
fs.writeFileSync(path.join(P, 'src/subpos.js'), '// generated by tools/subplace.mjs (caption placement from an emptiness map)\nconst SUBPOS = ' + JSON.stringify(res.out) + ';\n');
fs.writeFileSync(path.join(P, 'review/qa/subplace.json'), JSON.stringify(res.info, null, 1));
console.log('placed', Object.keys(res.out).length, 'fallback', res.info.filter((i) => i.fallback).length); await b.close();
