"""comic_script.md -> src/script.js (const SCRIPT = [...beats]) with per-beat durations.
Hold rule: each lettered item reads at 2.5 words/s, min 2 s per beat; items enter staggered.
  python tools/parse_script.py
"""
import json, re, os
D = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
txt = open(os.path.join(D, 'comic_script.md'), encoding='utf8').read()
beats, scene, credit_mode = [], None, False
for line in txt.splitlines():
    m = re.match(r'^## (\d+)\. (.+?) \(', line)
    if m:
        scene = int(m.group(1)); credit_mode = scene == 2; continue
    m = re.match(r'^\*\*(\d+\.\d+b?)\*\*\s*(.*)$', line)
    if m:
        bid, rest = m.groups()
        mm = re.match(r'\[(PANELS|PARALLAX): (.+)\]', rest)
        mode, desc = (mm.group(1), mm.group(2)) if mm else ('PANELS', rest.strip())   # credits cards are panels
        beats.append(dict(id=bid, scene=scene, mode=mode, desc=desc, items=[])); continue
    m = re.match(r'^- (CAPTION|BUBBLE|SFX)(?: \(([^)]*)\))?: ?(.*)$', line)
    if m and beats:
        kind, meta, text = m.groups()
        it = dict(kind=kind.lower(), text=text.strip())
        if kind == 'BUBBLE':
            who, typ = [s.strip() for s in meta.split(',')]
            it.update(who=who.lower().replace("é", "e").replace("'", ''), type=typ)
        if kind == 'CAPTION' and meta: it['type'] = 'phonescreen'
        if kind == 'SFX':                            # "SCREEEECH / BLAM BLAM BLAM / KSSSH" -> several SFX
            for s in [s.strip() for s in text.split(' / ')]:
                beats[-1]['items'].append(dict(kind='sfx', text=s))
            continue
        beats[-1]['items'].append(it)
    elif line.startswith('- ') and beats and 'no lettering' in line.lower():
        pass

def words(s): return len(re.findall(r"[\w']+", s))
for b in beats:
    read = sum(max(0.6, words(i['text']) / 2.5) for i in b['items'] if i['kind'] != 'sfx')
    n = len(b['items'])
    dur = max(2.0, 0.5 + 0.35 * max(0, n - 1) + read + 0.9)    # entry + stagger + reading + tail
    if b['scene'] == 2: dur = max(dur, 7.0)                       # credits cards ~7 s
    if b['mode'] == 'PARALLAX' and not b['items']: dur = 3.0
    if b['mode'] == 'PANELS': dur = max(dur, 3.6)
    if b['id'] in ('8.6', '0.2'): dur = max(dur, 5.5)
    b['dur'] = dur
# stretch each scene to the script's planned range (comic needs air: the reading pace is the minimum)
TARGET = {0: 30, 1: 70, 2: 70, 3: 65, 4: 70, 5: 90, 6: 75, 7: 70, 8: 50, 9: 15}
for s_, tg in TARGET.items():
    bs = [b for b in beats if b['scene'] == s_]; tot = sum(b['dur'] for b in bs)
    k = max(1.0, tg / tot) if tot else 1
    for b in bs: b['dur'] *= k
t = 0.0
for b in beats:
    b['dur'] = round(b['dur'] * 12) / 12; b['t0'] = round(t, 3); t += b['dur']
json.dump(beats, open(os.path.join(D, 'review', 'script.json'), 'w'), indent=1)
open(os.path.join(D, 'src', 'script.js'), 'w').write('// generated by tools/parse_script.py from comic_script.md\nconst SCRIPT = ' + json.dumps(beats) + ';\n')
print(len(beats), 'beats, total %.1f s' % t)
for s in range(10):
    bs = [b for b in beats if b['scene'] == s]
    if bs: print(s, len(bs), '%.1f-%.1f' % (bs[0]['t0'], bs[-1]['t0'] + bs[-1]['dur']))
