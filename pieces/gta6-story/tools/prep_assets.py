"""Copy the finished layers into assets/ at display size (webp keeps alpha small) and measure each
character layer: alpha bbox + mouth point (YuNet landmarks) -> src/meta.js (bubble tails aim at the mouth).
  .venv/bin/python pieces/gta6-story/tools/prep_assets.py
"""
import glob, json, os, sys
import cv2, numpy as np
from PIL import Image
D = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.dirname(os.path.dirname(D))
sys.path.insert(0, os.path.join(R, 'styles/gta6/tools'))
import face_id
A = os.path.join(D, 'assets'); os.makedirs(A, exist_ok=True)
meta = {}

def char(src, name):
    im = Image.open(src).convert('RGBA')
    im = im.resize((1920, round(1920 * im.height / im.width)), Image.LANCZOS)
    im.save(os.path.join(A, name + '.webp'), quality=88, method=5)
    a = np.array(im)
    ys, xs = np.nonzero(a[..., 3] > 128)
    bgr = cv2.cvtColor(a[..., :3], cv2.COLOR_RGB2BGR)
    bgr[a[..., 3] < 128] = (200, 180, 215)
    f = face_id.faces(bgr, 0.5)
    m = dict(w=im.width, h=im.height, box=[int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())])
    if len(f):
        f = sorted(f, key=lambda r: -r[2] * r[3])[0]
        m['face'] = [round(float(v)) for v in f[:4]]
        m['mouth'] = [round(float((f[10] + f[12]) / 2)), round(float((f[11] + f[13]) / 2))]
    else:   # no face found: top-centre of the silhouette
        m['mouth'] = [int(np.median(xs[ys < ys.min() + 60])), int(ys.min() + 0.08 * (ys.max() - ys.min()))]
        m['noface'] = True
    meta[name] = m

for p in sorted(glob.glob(os.path.join(D, 'chars/*_final.png'))):
    char(p, os.path.basename(p)[:-10])
for p in sorted(glob.glob(os.path.join(R, 'pieces/gta6-parallax-16x9/assets/c_*.png'))):
    char(p, 'cr_' + os.path.basename(p)[2:-4])
for p in sorted(glob.glob(os.path.join(D, 'bg/*.jpg'))):
    Image.open(p).convert('RGB').resize((1920, 1080), Image.LANCZOS).save(os.path.join(A, os.path.basename(p)), quality=86)
for n in ['brian_plate', 'drequan_plate', 'boobie_plate', 'bay_plate', 'raul_plate', 'jl_plate', 'dimez_plate', 'cal_plate']:
    Image.open(os.path.join(R, f'pieces/gta6-parallax-16x9/assets/{n}.jpg')).convert('RGB').resize((1920, 1080), Image.LANCZOS).save(os.path.join(A, n + '.jpg'), quality=86)
open(os.path.join(D, 'src/meta.js'), 'w').write('// generated by tools/prep_assets.py: layer size, alpha box, face box, mouth point (layer px)\nconst META = ' + json.dumps(meta) + ';\n')
tot = sum(os.path.getsize(os.path.join(A, f)) for f in os.listdir(A))
print(len(meta), 'char layers;', len(os.listdir(A)), 'files', round(tot / 1e6, 1), 'MB')
print({k: ('NOFACE' if v.get('noface') else v['mouth']) for k, v in meta.items()})
