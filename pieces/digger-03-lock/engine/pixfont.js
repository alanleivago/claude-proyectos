const NARROW = { ' ': 3, '.': 3, ':': 3, '!': 3, "'": 3 };
const hexRGB = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
export function textWidth(s, sc) { let w = 0; for (const ch of s.toUpperCase()) w += ((NARROW[ch] || 5) + 1) * sc; return w - sc; }
// draw centred at (x, y) on a 2D context; returns the box [X, Y, w, h]
export function bitText(ctx, s, x, y, sc = 2, fg = '#ffffff', { outline = '#040412', plate = null, border = null, pad = 3 } = {}) {
  s = s.toUpperCase(); const w = textWidth(s, sc), h = 7 * sc; let X = Math.round(x - w / 2); const Y = Math.round(y - h / 2);
  if (plate) {
    ctx.fillStyle = '#040412'; ctx.fillRect(X - pad - 2, Y - pad - 2, w + 2 * pad + 4, h + 2 * pad + 4);
    if (border) { ctx.fillStyle = border; ctx.fillRect(X - pad - 1, Y - pad - 1, w + 2 * pad + 2, h + 2 * pad + 2); }
    ctx.fillStyle = plate; ctx.fillRect(X - pad, Y - pad, w + 2 * pad, h + 2 * pad);
  }
  const cells = []; let cx = X;
  for (const ch of s) {
    const g = G[ch] || G['?'], cw = NARROW[ch] || 5, off = cw < 5 ? Math.floor((5 - cw) / 2) : 0;
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (g[r][c] === '#') cells.push([cx + (c - off) * sc, Y + r * sc]);
    cx += (cw + 1) * sc;
  }
  if (outline && !plate) { ctx.fillStyle = outline; for (const [px, py] of cells) ctx.fillRect(px - sc, py - sc, sc * 3, sc * 3); }
  ctx.fillStyle = fg; for (const [px, py] of cells) ctx.fillRect(px, py, sc, sc);
  return [X, Y, w, h];
}
